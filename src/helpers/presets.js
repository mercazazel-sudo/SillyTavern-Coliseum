/** Итоговый системный промпт помощника: общая работа, характер, свои правила, в конце навык «собрать персонажа» (последнее запоминается лучше). */
export function buildSystemPrompt(helper) {
  const personality = String(helper?.personality ?? '').trim();
  const extra = String(helper?.prompt ?? '').trim();
  return [BASE_PROMPT, personality, extra, SKILL_PROMPT].filter(Boolean).join('\n\n');
}

/**
 * Проверяет, есть ли файлы аватаров; у предустановок без файла картинка убирается,
 * и вместо неё показывается цветной кружок с буквой. Вызывается один раз при старте.
 */
export async function resolveAvatars() {
  const jobs = [];
  for (const set of SETS) {
    for (const helper of set.helpers) {
      if (!helper.avatar) continue;
      jobs.push(fetch(helper.avatar, { method: 'HEAD', cache: 'no-cache' })
        .then(res => { if (!res.ok) helper.avatar = ''; })
        .catch(() => { helper.avatar = ''; }));
    }
  }
  await Promise.all(jobs);
}
